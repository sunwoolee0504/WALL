from functools import partial

import numpy as np
import torch as th

from components.episode_buffer import EpisodeBatch
from components.wolfpack import attack_actions, select_followup
from envs import REGISTRY as env_REGISTRY


class EpisodeRunner:
    """Single-environment collector with issued-action policy history.

    Replay stores policy actions separately from actions executed by the attacked
    environment. Counterfactual predictor labels are generated by the learner
    only for sampled origins, so collection does no speculative model adaptation.
    """

    def __init__(self, args, logger):
        self.args = args
        self.logger = logger
        self.batch_size = args.batch_size_run
        if self.batch_size != 1:
            raise ValueError("WALL EpisodeRunner requires batch_size_run=1")
        self.env = env_REGISTRY[args.env](**args.env_args)
        self.episode_limit = self.env.episode_limit
        self.t = self.t_env = 0
        self.train_returns, self.test_returns = [], []
        self.train_stats, self.test_stats = {}, {}
        self.wolfpack_returns, self.test_wolfpack_returns = [], []
        self.wolfpack_stats, self.test_wolfpack_stats = {}, {}
        self.log_train_stats_t = -1000000

    def setup(self, scheme, groups, preprocess, mac, qdifference_transformer, planning_transformer):
        self.new_batch = partial(EpisodeBatch, scheme, groups, self.batch_size,
                                 self.episode_limit + 1, preprocess=preprocess,
                                 device=self.args.device)
        self.mac = mac
        self.qdiff_transformer = qdifference_transformer
        self.planning_transformer = planning_transformer

    def setup_mac_for_attack(self, mac):
        """Compatibility hook: Q-output adaptation needs no policy clone."""

    def setup_learner(self, learner):
        self.learner = learner

    def get_env_info(self):
        return self.env.get_env_info()

    def save_replay(self):
        self.env.save_replay()

    def close_env(self):
        self.env.close()

    def reset(self):
        self.batch = self.new_batch()
        self.env.reset()
        self.t = 0

    def _store_observation(self):
        # Array stacking avoids torch constructing a tensor from lists of arrays.
        self.batch.update({
            "state": np.asarray([self.env.get_state()]),
            "avail_actions": np.asarray([self.env.get_avail_actions()]),
            "obs": np.asarray([self.env.get_obs()]),
        }, ts=self.t)

    def _store_actions(self, actions, forced_actions, **data):
        data["actions"] = actions
        if "forced_actions" in self.batch.scheme:
            data["forced_actions"] = forced_actions
        self.batch.update(data, ts=self.t)

    def _policy(self, test_mode):
        all_q = self.mac.forward(self.batch, t=self.t, test_mode=test_mode)
        avail = self.batch["avail_actions"][:, self.t]
        actions = self.mac.action_selector.select_action(all_q, avail, self.t_env, test_mode)
        return all_q, actions, avail

    @th.no_grad()
    def get_attack_step(self, pre_initial_attack_step=None):
        """Sample Eq. (3)'s first probability from a fixed rolling horizon.

        The compatibility argument is intentionally unused: elapsed time since
        the last burst must not truncate the paper's horizon. Initial-agent
        sampling is independent and happens only after deciding to attack.
        """
        horizon = int(self.args.attack_period)
        if horizon < 1:
            raise ValueError("attack_period must be positive")
        if getattr(self.args, "scheduler_mask_episode_end", False):
            horizon = min(horizon, self.episode_limit - self.t)
        updates = getattr(self.learner, "wall_updates", 0)
        if updates < getattr(self.args, "planner_warmup_updates", 32):
            probability = 1.0 / horizon
        else:
            start = max(0, self.t - self.args.trans_input_len + 1)
            states = self.batch["state"][:, start:self.t + 1]
            times = th.arange(start, self.t + 1, device=states.device).unsqueeze(0)
            logits = self.qdiff_transformer(times, states, last_only=True)[:, -1, :horizon].float()
            temperature = float(self.args.temperature)
            if temperature <= 0:
                raise ValueError("temperature must be positive")
            probability = th.softmax(logits / temperature, dim=-1)[0, 0]
        decide = bool(th.rand((), device=self.batch.device) < probability)
        initial = int(th.randint(self.args.n_agents, (), device=self.batch.device)) if decide else -1
        return decide, initial

    def run(self, test_mode=False):
        return self._run_episode(test_mode, attacked=False)

    def run_wolfpack_attacker(self, test_mode=False):
        if not getattr(self.args, "init_agent_random", True):
            raise ValueError("The state-only WALL scheduler requires init_agent_random=True")
        return self._run_episode(test_mode, attacked=True)

    @th.no_grad()
    def _run_episode(self, test_mode, attacked):
        modules = [getattr(self.mac, "agent", None), self.qdiff_transformer,
                   self.planning_transformer]
        modules = [module for module in modules if module is not None]
        modes = [module.training for module in modules]
        for module in modules:
            module.eval()
        try:
            return self._collect(test_mode, attacked)
        finally:
            for module, mode in zip(modules, modes):
                module.train(mode)

    def _collect(self, test_mode, attacked):
        self.reset()
        self.mac.init_hidden(batch_size=self.batch_size)
        terminated = False
        episode_return = 0.0
        env_info = {}
        budget = int(self.args.num_attack_test if test_mode else self.args.num_attack_train) if attacked else 0
        duration = int(getattr(self.args, "attack_duration", 3))
        if duration < 0 or budget < 0:
            raise ValueError("Attack duration and budget must be nonnegative")
        max_bursts = budget // (duration + 1)
        changed_steps = bursts = followup_remaining = 0
        followup_group = th.empty(1, 0, dtype=th.long, device=self.args.device)
        initial_agent = -1

        while not terminated:
            self._store_observation()
            all_q, actions, avail = self._policy(test_mode)
            executed = actions
            state = self.batch["state"][:, self.t]
            initial_this_step = -1
            if followup_remaining > 0:
                if changed_steps < budget:
                    mask = th.zeros_like(actions, dtype=th.bool)
                    valid = followup_group[0] >= 0
                    mask[0, followup_group[0, valid]] = True
                    executed = attack_actions(self.learner.mixer, self.args, all_q, state,
                                              actions, avail, mask)
                # A burst always has exactly duration consecutive follow-up
                # slots, including slots whose legal minimizer is a no-op.
                followup_remaining -= 1
            elif bursts < max_bursts and changed_steps < budget:
                method = self.args.init_attack_step_method
                if method == "planner":
                    should_attack, initial_agent = self.get_attack_step()
                elif method == "random":
                    should_attack = bool(th.rand(()) < getattr(self.args, "random_attack_probability", 0.1))
                    initial_agent = int(th.randint(self.args.n_agents, ())) if should_attack else -1
                else:
                    raise ValueError("Unknown init_attack_step_method: %s" % method)
                if should_attack:
                    mask = th.zeros_like(actions, dtype=th.bool)
                    mask[:, initial_agent] = True
                    executed = attack_actions(self.learner.mixer, self.args, all_q, state,
                                              actions, avail, mask)
                    if bool((executed != actions).any()):
                        bursts += 1
                        initial_this_step = initial_agent
                        followup_remaining = duration
                        if duration:
                            # select_followup narrowly enables input-Q autograd.
                            followup_group = select_followup(
                                self.learner.mixer, self.args, all_q, state, actions,
                                executed, avail,
                                th.tensor([initial_agent], device=actions.device),
                                obs=self.batch["obs"][:, self.t])
            changed_steps += int(bool((executed != actions).any()))
            reward, terminated, env_info = self.env.step(executed[0].cpu().numpy())
            episode_return += reward
            data = {
                "reward": [(reward,)],
                "terminated": [(terminated != env_info.get("episode_limit", False),)],
            }
            # These fields are optional for older replay schemes. Only actual
            # burst metadata is meaningful; no fake per-step counterfactuals.
            if "initial_agent" in self.batch.scheme:
                data["initial_agent"] = [[initial_this_step]]
            if "followup_agents" in self.batch.scheme:
                group = followup_group if (followup_remaining or initial_this_step >= 0) else th.full_like(followup_group, -1)
                if group.shape[-1] != self.args.num_followup_agents:
                    group = th.full((1, self.args.num_followup_agents), -1, device=actions.device, dtype=th.long)
                data["followup_agents"] = group
            self._store_actions(actions, executed, **data)
            self.t += 1

        self._store_observation()
        _, actions, _ = self._policy(test_mode)
        self._store_actions(actions, actions)
        if attacked:
            env_info = dict(env_info, attack_changed_steps=changed_steps,
                            attack_bursts=bursts, attack_budget=budget)
        self._record(episode_return, env_info, test_mode, attacked)
        return self.batch

    def _record(self, episode_return, env_info, test_mode, attacked):
        if attacked:
            stats = self.test_wolfpack_stats if test_mode else self.wolfpack_stats
            returns = self.test_wolfpack_returns if test_mode else self.wolfpack_returns
            prefix = "test_Wolfpack_" if test_mode else "Wolfpack_"
        else:
            stats = self.test_stats if test_mode else self.train_stats
            returns = self.test_returns if test_mode else self.train_returns
            prefix = "test_" if test_mode else ""
        for key, value in env_info.items():
            if isinstance(value, (int, float, np.number)):
                stats[key] = stats.get(key, 0) + value
        stats["n_episodes"] = stats.get("n_episodes", 0) + 1
        stats["ep_length"] = stats.get("ep_length", 0) + self.t
        returns.append(episode_return)
        if not test_mode:
            self.t_env += self.t
        if test_mode:
            if len(returns) >= self.args.test_nepisode:
                self._log(returns, stats, prefix)
        elif self.t_env - self.log_train_stats_t >= self.args.runner_log_interval:
            self._log(returns, stats, prefix)
            if hasattr(self.mac.action_selector, "epsilon"):
                self.logger.log_stat("epsilon", self.mac.action_selector.epsilon, self.t_env)
            self.log_train_stats_t = self.t_env

    def _log(self, returns, stats, prefix):
        self.logger.log_stat(prefix + "return_mean", np.mean(returns), self.t_env)
        self.logger.log_stat(prefix + "return_std", np.std(returns), self.t_env)
        returns.clear()
        for key, value in stats.items():
            if key != "n_episodes":
                self.logger.log_stat(prefix + key + "_mean", value / stats["n_episodes"], self.t_env)
        stats.clear()
